#!/usr/bin/env python3
"""Generates CoopEnemyActionFuncs.inc: where each enemy type keeps its actionFunc.

Enemy puppets on a client receive the host's actionFunc (as an offset inside the binary) because many enemy draw
functions compare it. The field sits at a different offset in every enemy struct, so this script lists, for every
enemy overlay (profile category ACTORCAT_ENEMY, or a type that switches to it), the struct and its actionFunc field.
The offsets themselves come from offsetof() at compile time, never from the N64 offset comments in the headers.

Run from this folder after the decomp headers change:  python gen_enemy_action_funcs.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MM = os.path.normpath(os.path.join(HERE, '..', '..'))
OVERLAYS = os.path.join(MM, 'src', 'overlays', 'actors')
ACTOR_TABLE = os.path.join(MM, 'include', 'tables', 'actor_table.h')
OUT = os.path.join(HERE, 'CoopEnemyActionFuncs.inc')

# Types whose profile is not ACTORCAT_ENEMY but that switch to it (see CoopEnemyTypes.cpp, kBecomeEnemies).
BECOME_ENEMIES = {'En_Wf', 'En_Sw', 'En_Raf', 'En_Tubo_Trap'}


def actor_enums():
    names = {}
    for m in re.finditer(r'DEFINE_ACTOR\(\s*(\w+),\s*(ACTOR_\w+),', open(ACTOR_TABLE, encoding='utf-8').read()):
        names[m.group(1)] = m.group(2)
    return names


def profile_category(source):
    m = re.search(r'ActorProfile\s+\w+_Profile\s*=\s*\{\s*/\*[^*]*\*/\s*\w+,\s*/\*[^*]*\*/\s*(ACTORCAT_\w+)', source)
    if m is None:
        m = re.search(r'ActorProfile\s+\w+_Profile\s*=\s*\{\s*\w+,\s*(ACTORCAT_\w+)', source)
    return m.group(1) if m else None


def main():
    enums = actor_enums()
    rows = []
    for name in sorted(enums):
        folder = os.path.join(OVERLAYS, 'ovl_' + name)
        if not os.path.isdir(folder):
            continue
        sources = [f for f in os.listdir(folder) if f.endswith('.c')]
        headers = [f for f in os.listdir(folder) if f.endswith('.h')]
        if not sources or not headers:
            continue
        source = open(os.path.join(folder, sources[0]), encoding='utf-8', errors='replace').read()
        category = profile_category(source)
        if category != 'ACTORCAT_ENEMY' and name not in BECOME_ENEMIES:
            continue
        for header in headers:
            text = open(os.path.join(folder, header), encoding='utf-8', errors='replace').read()
            m = re.search(r'typedef struct (\w+) \{\s*/\*[^*]*\*/\s*Actor actor;(.*?)\}\s*\1;', text, re.S)
            if m is None:
                continue
            if re.search(r'\bactionFunc;', m.group(2)):
                rows.append((enums[name], 'ovl_%s/%s' % (name, header), m.group(1)))
            break
    with open(OUT, 'w', encoding='utf-8', newline='\n') as out:
        out.write('// Generated by gen_enemy_action_funcs.py. Do not edit.\n')
        out.write('// Include once with ENEMY_ACTION_FUNC_INCLUDES defined (the struct headers), then with\n')
        out.write('// ENEMY_ACTION_FUNC(actor id, struct) defined (the table).\n')
        out.write('#if defined(ENEMY_ACTION_FUNC_INCLUDES)\n')
        for enum, header, struct in rows:
            out.write('#include "overlays/actors/%s"\n' % header)
        out.write('#else\n')
        for enum, header, struct in rows:
            out.write('ENEMY_ACTION_FUNC(%s, %s)\n' % (enum, struct))
        out.write('#endif\n')
    print('%d enemy types with an actionFunc -> %s' % (len(rows), OUT))


if __name__ == '__main__':
    main()
